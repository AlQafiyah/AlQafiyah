-- تسجيل حدث الإعلان؛ لا يمكن إدراج أحداث مباشرة في الجدول.
CREATE OR REPLACE FUNCTION public.qafiyah_v21_record_ad_event(p_ad_id uuid,p_event_type text,p_visitor_key text)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 IF p_event_type NOT IN ('view','click') OR length(p_visitor_key) NOT BETWEEN 12 AND 100 THEN RETURN; END IF;
 IF NOT EXISTS(SELECT 1 FROM public.qafiyah_ads a WHERE a.id=p_ad_id AND a.is_active AND (a.starts_at IS NULL OR a.starts_at<=now()) AND (a.ends_at IS NULL OR a.ends_at>=now())) THEN RETURN; END IF;
 IF EXISTS(SELECT 1 FROM public.qafiyah_ad_events e WHERE e.ad_id=p_ad_id AND e.visitor_key=p_visitor_key AND e.event_type=p_event_type AND e.created_at>now()-interval '3 seconds') THEN RETURN; END IF;
 INSERT INTO public.qafiyah_ad_events(ad_id,event_type,visitor_key,user_id) VALUES(p_ad_id,p_event_type,p_visitor_key,auth.uid());
END;$$;
REVOKE ALL ON FUNCTION public.qafiyah_v21_record_ad_event(uuid,text,text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.qafiyah_v21_record_ad_event(uuid,text,text) TO anon,authenticated;

CREATE OR REPLACE FUNCTION public.qafiyah_v21_ad_stats()
RETURNS TABLE(ad_id uuid,views bigint,clicks bigint,unique_viewers bigint,unique_accounts bigint)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
BEGIN
 IF public.qafiyah_my_role() NOT IN ('owner','manager') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
 RETURN QUERY SELECT a.id,count(e.id) FILTER(WHERE e.event_type='view'),count(e.id) FILTER(WHERE e.event_type='click'),count(DISTINCT e.visitor_key) FILTER(WHERE e.event_type='view'),count(DISTINCT e.user_id) FILTER(WHERE e.event_type='view') FROM public.qafiyah_ads a LEFT JOIN public.qafiyah_ad_events e ON e.ad_id=a.id GROUP BY a.id;
END;$$;
REVOKE ALL ON FUNCTION public.qafiyah_v21_ad_stats() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.qafiyah_v21_ad_stats() TO authenticated;

