-- بحث آمن في auth.users من لوحة الصلاحيات، لا يسمح لزوار الموقع باستخدامه.
CREATE OR REPLACE FUNCTION public.qafiyah_v21_search_users(search_term text)
RETURNS TABLE(user_id uuid,display_name text,email text,phone text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=public,auth,pg_temp AS $$
BEGIN
 IF public.qafiyah_my_role() NOT IN ('owner','manager','supervisor') THEN RAISE EXCEPTION 'غير مصرح'; END IF;
 IF length(trim(coalesce(search_term,'')))<2 THEN RETURN; END IF;
 RETURN QUERY SELECT u.id,trim(concat_ws(' ',p.first_name,p.last_name)),u.email::text,p.phone::text
 FROM auth.users u LEFT JOIN public.profiles p ON p.id=u.id
 WHERE u.id::text=trim(search_term) OR u.email ILIKE '%'||replace(replace(trim(search_term),'%','\%'),'_','\_')||'%' ESCAPE '\'
 OR concat_ws(' ',p.first_name,p.last_name) ILIKE '%'||replace(replace(trim(search_term),'%','\%'),'_','\_')||'%' ESCAPE '\'
 OR p.phone ILIKE '%'||replace(replace(trim(search_term),'%','\%'),'_','\_')||'%' ESCAPE '\'
 ORDER BY u.created_at DESC LIMIT 25;
END;$$;
REVOKE ALL ON FUNCTION public.qafiyah_v21_search_users(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.qafiyah_v21_search_users(text) TO authenticated;

